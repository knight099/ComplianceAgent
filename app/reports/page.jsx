"use client";
import { useRef, useState } from "react";
import { Workspace, Panel } from "../ui/workspace";

const outcomes = ["EXCESS_ACCESS", "MISSING_EXPECTED_GRANT", "APPROVED_EXCEPTION", "INSUFFICIENT_EVIDENCE", "AS_EXPECTED"];
function validReport(report) {
  const string = value => typeof value === "string";
  return report?.format === "complyos.access-review/v1" &&
    [report.source, report.observedAt, report.policy?.id, report.policy?.version, report.policy?.reference,
      report.policy?.reviewer, report.hrRevision, report.hrObserved].every(string) &&
    Array.isArray(report.rows) && report.rows.every(row => row && string(row.employeeId) &&
      (row.businessRole === null || string(row.businessRole)) &&
      Array.isArray(row.resource) && row.resource.length === 2 && row.resource.every(string) &&
      [row.expected, row.observed].every(value => [null, "none", "read"].includes(value)) &&
      outcomes.includes(row.outcome));
}

export default function Reports() {
  const [report, setReport] = useState(null);
  const [error, setError] = useState("");
  const [filter, setFilter] = useState("");
  const selection = useRef(0);
  async function open(event) {
    const [file] = event.target.files;
    if (!file) return;
    const revision = ++selection.current;
    setError("");
    setReport(null);
    setFilter("");
    try {
      const value = JSON.parse(await file.text());
      if (!validReport(value)) throw Error();
      if (revision === selection.current) setReport(value);
    } catch {
      if (revision === selection.current) setError("Choose a valid ComplyOS access review JSON file.");
    }
  }
  const rows = report?.rows.filter(row => !filter || row.outcome === filter) ?? [];
  return <Workspace><main>
    <a href="/">ComplyOS overview</a>
    <h1>Access review reports</h1>
    <p>Open a report generated by the read-only relay. The file is read locally in this browser.</p>
    <label>Report file <input type="file" accept=".json,application/json" onChange={open} /></label>
    {error && <p role="alert">{error}</p>}
    {report && <Panel title={report.source}>
      <p>Collected {report.observedAt} · HR revision {report.hrRevision} observed {report.hrObserved}</p>
      <p>{report.policy.id} · Version {report.policy.version} · Reviewed by {report.policy.reviewer} · {report.policy.reference}</p>
      <label>Outcome <select value={filter} onChange={e => setFilter(e.target.value)}>
        <option value="">All outcomes</option>
        {outcomes.map(value => <option key={value}>{value}</option>)}
      </select></label>
      <p>{rows.length} matching observations</p>
      {rows.map((row, index) => <details key={index}>
        <summary>{row.employeeId} · {row.businessRole || "Unmapped role"} · {row.resource.join(".")} · {row.outcome}</summary>
        <p>Observed {row.observed ?? "unknown"} · Expected {row.expected ?? "unmapped"}</p>
        <pre style={{whiteSpace:"pre-wrap", overflowWrap:"anywhere"}}>{JSON.stringify({
          databaseRole: row.databaseRole, classification: row.classification,
          exception: row.exception, evidence: row.evidence,
        }, null, 2)}</pre>
      </details>)}
    </Panel>}
    <p><a href="/operations">Offboarding assessments and reconciliation reports</a></p>
  </main></Workspace>;
}
